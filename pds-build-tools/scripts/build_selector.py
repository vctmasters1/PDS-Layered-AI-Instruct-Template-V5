# ANSI color codes
class Colors:
    RESET = '\033[0m'
    BOLD = '\033[1m'
    DIM = '\033[2m'
    CYAN = '\033[96m'
    GREEN = '\033[92m'
    YELLOW = '\033[93m'
    RED = '\033[91m'
    BLUE = '\033[94m'
    WHITE = '\033[97m'

def cprint(msg: str, color: str = Colors.WHITE) -> None:
    """Print colored message"""
    print(f"{color}{msg}{Colors.RESET}")

def header(msg: str) -> None:
    """Print section header"""
    print(f"\n{Colors.CYAN}{Colors.BOLD}{'='*70}{Colors.RESET}")
    print(f"{Colors.CYAN}{Colors.BOLD}{msg:^70}{Colors.RESET}")
    print(f"{Colors.CYAN}{Colors.BOLD}{'='*70}{Colors.RESET}\n")

def success(msg: str) -> None:
    """Print success message"""
    cprint(f"[+] {msg}", Colors.GREEN)

def error(msg: str) -> None:
    """Print error message"""
    cprint(f"[-] {msg}", Colors.RED)

def warning(msg: str) -> None:
    """Print warning message"""
    cprint(f"[!] {msg}", Colors.YELLOW)

def info(msg: str) -> None:
    """Print info message"""
    cprint(f"[*] {msg}", Colors.BLUE)

def has_devcontainer_cli() -> bool:
    """Check if devcontainers CLI is installed"""
    return shutil.which("devcontainer") is not None

def get_devcontainer_path(board: str) -> Optional[Path]:
    """Get the devcontainer path for a board.

    Container name is always DEV-Container-<board_name>, where board_name
    is the directory name under Device/pds/pds_hal/board/.
    e.g.  esp32c3_sm    -> DEV-Container-esp32c3_sm
          esp32_node32s -> DEV-Container-esp32_node32s
    """
    workspace = Path(__file__).parent.parent.parent
    container_path = workspace / "Device" / f"DEV-Container-{board}"
    if container_path.exists():
        return container_path
    return None


def scaffold_role_dir(board: str, hwrev: str, role: str) -> bool:
    """Create minimal pds_process_action.c + usrset_defaults.h for a role that has no dir.

    Without these files, the linker fails with 'undefined reference to pds_role_init'
    after a full compile — a very late and confusing failure.  This function detects
    the missing files before the build starts and writes stubs so the firmware at
    least compiles.  The developer can then fill in telemetry wiring at their leisure.

    Returns True if any file was written (scaffolded), False if both already existed.
    """
    workspace = Path(__file__).parent.parent.parent
    role_dir = workspace / "Device" / "pds" / "pds_hal" / "board" / board / hwrev / role
    pa_file = role_dir / "pds_process_action.c"
    ud_file = role_dir / "usrset_defaults.h"

    if pa_file.exists() and ud_file.exists():
        return False

    role_tag = role.replace("-", "_").upper()
    ts = datetime.utcnow().strftime("%Y-%m-%d UTC")
    role_dir.mkdir(parents=True, exist_ok=True)

    if not ud_file.exists():
        ud_file.write_text(
            f'/**\n'
            f' * @file usrset_defaults.h\n'
            f' * @brief Usrset defaults for {role} — scaffold by build_selector.py ({ts})\n'
            f' *        board: {board} / {hwrev}\n'
            f' */\n'
            f'#ifndef PDS_USRSET_DEFAULTS_H\n'
            f'#define PDS_USRSET_DEFAULTS_H\n'
            f'\n'
            f'#include "pds_usrset.h"\n'
            f'\n'
            f'#ifdef __cplusplus\n'
            f'extern "C" {{\n'
            f'#endif\n'
            f'\n'
            f'static const pds_usrset_default_t pds_usrset_defaults[] = {{\n'
            f'    {{ "telemetry_interval_ms", 5000.0f }},\n'
            f'}};\n'
            f'\n'
            f'#define PDS_USRSET_DEFAULTS_COUNT \\\n'
            f'    ((uint16_t)(sizeof(pds_usrset_defaults) / sizeof(pds_usrset_defaults[0])))\n'
            f'\n'
            f'#ifdef __cplusplus\n'
            f'}}\n'
            f'#endif\n'
            f'\n'
            f'#endif /* PDS_USRSET_DEFAULTS_H */\n',
            encoding="utf-8"
        )

    if not pa_file.exists():
        pa_file.write_text(
            f'/**\n'
            f' * @file pds_process_action.c\n'
            f' * @brief Role scaffold for {role} — auto-generated by build_selector.py ({ts})\n'
            f' *        board: {board} / {hwrev}\n'
            f' *\n'
            f' * SCAFFOLD: This file was missing for this role/hwrev combination and was\n'
            f' * created automatically so the firmware compiles.  Edit the telemetry\n'
            f' * provider below to match your hardware wiring, then rebuild.\n'
            f' */\n'
            f'\n'
            f'#include "freertos/FreeRTOS.h"\n'
            f'#include "esp_log.h"\n'
            f'#include "esp_err.h"\n'
            f'#include "nvs_flash.h"\n'
            f'\n'
            f'#include "pds_usrset.h"\n'
            f'#include "pds_telemetry.h"\n'
            f'#include "usrset_defaults.h"\n'
            f'\n'
            f'static const char *TAG = "{role_tag}_ROLE";\n'
            f'\n'
            f'static esp_err_t {role_tag}_telemetry_provider(pds_teldata_packet_t *packet)\n'
            f'{{\n'
            f'    /* TODO: call pds_telemetry_add_adc/pwm/gpio for each sensor/actuator */\n'
            f'    (void)packet;\n'
            f'    return ESP_OK;\n'
            f'}}\n'
            f'\n'
            f'esp_err_t pds_role_init(void)\n'
            f'{{\n'
            f'    esp_err_t ret = pds_usrset_init(pds_usrset_defaults, PDS_USRSET_DEFAULTS_COUNT);\n'
            f'    if (ret != ESP_OK) {{\n'
            f'        ESP_LOGW(TAG, "pds_usrset_init: %s", esp_err_to_name(ret));\n'
            f'        return ret;\n'
            f'    }}\n'
            f'    ret = pds_usrset_load_nvs();\n'
            f'    if (ret == ESP_ERR_NVS_NOT_FOUND) {{\n'
            f'        ESP_LOGI(TAG, "No saved usrset -- using defaults");\n'
            f'        ret = ESP_OK;\n'
            f'    }} else if (ret != ESP_OK) {{\n'
            f'        ESP_LOGW(TAG, "pds_usrset_load_nvs: %s", esp_err_to_name(ret));\n'
            f'        return ret;\n'
            f'    }}\n'
            f'    pds_telemetry_register_provider({role_tag}_telemetry_provider);\n'
            f'    ESP_LOGI(TAG, "Role init OK -- %d usrset defaults", PDS_USRSET_DEFAULTS_COUNT);\n'
            f'    return ESP_OK;\n'
            f'}}\n'
            f'\n'
            f'esp_err_t pds_process_action(void)\n'
            f'{{\n'
            f'    return ESP_OK;\n'
            f'}}\n',
            encoding="utf-8"
        )

    return True


